CREATE TABLE IF NOT EXISTS ai_tool_call_log (
    id BIGINT NOT NULL AUTO_INCREMENT,
    request_id VARCHAR(128) NOT NULL,
    attempt_no INT NOT NULL DEFAULT 1,
    account_id BIGINT NULL,
    business_type VARCHAR(64) NOT NULL,
    business_id VARCHAR(128) NULL,
    purpose VARCHAR(64) NOT NULL,
    provider VARCHAR(24) NOT NULL,
    slot_no INT NULL,
    key_fingerprint VARCHAR(32) NULL,
    model VARCHAR(128) NOT NULL,
    status VARCHAR(24) NOT NULL,
    http_status INT NULL,
    error_code VARCHAR(64) NULL,
    error_summary VARCHAR(500) NULL,
    prompt_tokens INT NULL,
    completion_tokens INT NULL,
    started_at DATETIME(3) NOT NULL,
    finished_at DATETIME(3) NULL,
    duration_ms BIGINT NULL,
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_ai_tool_request_attempt (request_id, attempt_no),
    KEY idx_ai_tool_status_started (status, started_at),
    KEY idx_ai_tool_account_started (account_id, started_at),
    KEY idx_ai_tool_provider_started (provider, started_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Interactive AI tool attempts without prompts, responses, or raw keys';
